"""A hook added since the base must say what it is; hooks already there without a label are the
worklist and are not refused. Built on a real tiny git repository so "since the base" is real."""

from __future__ import annotations

import importlib.util
import json
import subprocess
from pathlib import Path

SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "check_new_hooks_say_what_they_are.py"
_spec = importlib.util.spec_from_file_location("check_new_hooks", SCRIPT)
chk = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(chk)

_GIT = ["git", "-c", "user.email=t@example.com", "-c", "user.name=t", "-c", "commit.gpgsign=false"]


def _git(root: Path, *args: str) -> None:
    subprocess.run([*_GIT, "-C", str(root), *args], check=True, capture_output=True)


def _write_hooks(root: Path, files: dict[str, str]) -> None:
    hooks = root / ".claude" / "hooks"
    hooks.mkdir(parents=True, exist_ok=True)
    for name, body in files.items():
        (hooks / name).write_text(body, encoding="utf-8")
    settings = {
        "hooks": {
            "Stop": [{"hooks": [{"command": f"bash .claude/hooks/{n}"} for n in sorted(files)]}]
        }
    }
    (root / ".claude" / "settings.json").write_text(json.dumps(settings), encoding="utf-8")


def _base_repo(tmp_path: Path) -> Path:
    """A repo whose committed state is one unlabeled hook, as the live house is today."""
    _git(tmp_path, "init", "-q", "-b", "main")
    (tmp_path / "docs").mkdir()
    _write_hooks(tmp_path, {"old.sh": "#!/bin/bash\nexit 0\n"})
    _git(tmp_path, "add", "-A")
    _git(tmp_path, "commit", "-q", "-m", "base")
    return tmp_path


def test_a_new_hook_with_no_label_is_asked_what_it_is(tmp_path):
    root = _base_repo(tmp_path)
    _write_hooks(root, {"old.sh": "#!/bin/bash\nexit 0\n", "new.sh": "#!/bin/bash\nexit 0\n"})

    code, text = chk.check(root, "main")

    assert code == 1
    assert "new.sh" in text
    assert "scaffolding for something not built yet, or something only you can do" in text
    assert "old.sh" not in text, "an existing unlabeled hook is the worklist, not refused here"


def test_a_new_hook_that_says_what_it_is_passes(tmp_path):
    """Control: the same addition, with a label, goes through."""
    root = _base_repo(tmp_path)
    _write_hooks(
        root,
        {
            "old.sh": "#!/bin/bash\nexit 0\n",
            "new.sh": "#!/bin/bash\n# HOOK-ROLE: scaffold -- replaced by a surface in the router\n",
        },
    )
    code, text = chk.check(root, "main")
    assert code == 0, text


def test_an_unreadable_base_is_not_a_pass(tmp_path):
    root = _base_repo(tmp_path)
    code, text = chk.check(root, "no-such-ref")
    assert code == 2
    assert "NOT CHECKED" in text and "not a pass" in text
    assert chk.check(root, "main")[0] == 0, "control: a readable base with no additions is a pass"


def test_nothing_new_passes_even_with_unlabeled_old_hooks(tmp_path):
    root = _base_repo(tmp_path)
    code, _ = chk.check(root, "main")
    assert code == 0


def test_a_new_generated_doorbell_needs_no_hand_written_label(tmp_path):
    root = _base_repo(tmp_path)
    _write_hooks(
        root,
        {
            "old.sh": "#!/bin/bash\nexit 0\n",
            "bell.sh": "#!/bin/bash\n# GENERATED by divineos.core.doorbell_generator. Do not hand-edit\n",
        },
    )
    assert chk.check(root, "main")[0] == 0
